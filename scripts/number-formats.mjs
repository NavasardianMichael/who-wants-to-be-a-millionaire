#!/usr/bin/env node
/**
 * Writes `src/i18n/numberFormats.ts`: how each locale writes money and whole numbers,
 * read from Node's full ICU once, so the server and every browser format them the same way.
 *
 * Browsers ship trimmed ICU data. Chrome has no number data for Armenian, Georgian, Kazakh
 * and two dozen of our other locales and silently falls back to English, so a client
 * component that calls `Intl.NumberFormat` renders `$1,000,000` over the server's
 * `1 000 000 $` and fails hydration.
 *
 * Usage: node scripts/number-formats.mjs   (after adding a locale, or when
 * `tests/unit/i18n/numberFormats.spec.ts` says Node's ICU moved on)
 */
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUT = path.join(ROOT, 'src/i18n/numberFormats.ts')

const config = readFileSync(path.join(ROOT, 'src/i18n/config.ts'), 'utf8')
const LOCALES = [...config.match(/LOCALES = \[([^\]]*)\] as const/)[1].matchAll(/'([^']+)'/g)].map(([, locale]) => locale)

const SAMPLE = 1234567890

const patternOf = (locale, options) => {
  const format = new Intl.NumberFormat(locale, { ...options, maximumFractionDigits: 0 })
  const parts = format.formatToParts(SAMPLE)
  const first = parts.findIndex((part) => part.type === 'integer')
  const last = parts.findLastIndex((part) => part.type === 'integer')
  const lengths = parts.filter((part) => part.type === 'integer').map((part) => part.value.length)
  const digits = Array.from({ length: 10 }, (_, digit) => new Intl.NumberFormat(locale, options).formatToParts(digit))
    .map((each) => each.find((part) => part.type === 'integer').value)
    .join('')
  if (digits.length !== 10) throw new Error(`${locale}: digits outside the BMP (${digits})`)

  const pattern = {
    prefix: parts.slice(0, first).map((part) => part.value).join(''),
    suffix: parts.slice(last + 1).map((part) => part.value).join(''),
  }
  const group = parts.find((part) => part.type === 'group')?.value ?? ''
  const grouping = [lengths.at(-1), lengths.at(-2)]
  if (group !== ',') pattern.group = group
  if (group && (grouping[0] !== 3 || grouping[1] !== 3)) pattern.grouping = grouping
  if (group && !format.formatToParts(1000).some((part) => part.type === 'group')) pattern.minimumGrouping = 2
  if (digits !== '0123456789') pattern.digits = digits
  return pattern
}

/** Literal strings, with the invisible spaces and direction marks spelled out. */
const literal = (value) =>
  `'${value
    .replace(/'/g, "\\'")
    .replace(
      /[\u00a0\u061c\u2000-\u200f\u2028-\u202f\u2066-\u2069]/g,
      (char) => `\\u${char.charCodeAt(0).toString(16).padStart(4, '0')}`
    )}'`

const render = (pattern) =>
  `{ ${Object.entries(pattern)
    .map(([key, value]) => `${key}: ${typeof value === 'string' ? literal(value) : Array.isArray(value) ? `[${value.join(', ')}]` : value}`)
    .join(', ')} }`

const entries = LOCALES.map((locale) => {
  const money = patternOf(locale, { style: 'currency', currency: 'USD' })
  const number = patternOf(locale, {})
  return `  ${/^[a-z]+$/.test(locale) ? locale : `'${locale}'`}: {\n    money: ${render(money)},\n    number: ${render(number)},\n  },`
})

writeFileSync(
  OUT,
  `// Generated by \`pnpm i18n:formats\` (scripts/number-formats.mjs) from Node ${process.version}, ICU ${process.versions.icu}. Do not edit.
import type { Locale } from './config'

/** How one locale writes a whole number. Omitted fields are the English defaults. */
export interface NumberPattern {
  prefix: string
  suffix: string
  /** Group separator; empty when the locale does not group. Default \`,\`. */
  group?: string
  /** The first group's size from the right, then every later group's (Indian: 3, 2). Default 3, 3. */
  grouping?: readonly [number, number]
  /** 2 writes \`1000\` but \`16 000\`: a lone leading digit is not split off. Default 1. */
  minimumGrouping?: number
  /** The locale's ten digits, when they are not 0–9. */
  digits?: string
}

export const NUMBER_FORMATS: Record<Locale, { money: NumberPattern; number: NumberPattern }> = {
${entries.join('\n')}
}
`
)
console.log(`Wrote ${path.relative(ROOT, OUT)} (${LOCALES.length} locales)`)
